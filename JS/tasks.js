// ===================================
// Задача 1
// Вывод чисел от 1 до 20, пропуская кратные 4
// ===================================
console.log('=== Задача 1: Числа от 1 до 20 (без кратных 4) ===');

for (let i = 1; i <= 20; i++) {
    if (i % 4 === 0) {
        continue; // Пропускаем числа, делящиеся на 4
    }
    console.log(i);
}

// ===================================
// Задача 2
// Вычисление факториала числа
// ===================================
console.log('\n=== Задача 2: Факториал числа ===');

const num = parseInt(prompt('Введите число для вычисления факториала:'));

if (isNaN(num) || num < 0) {
    console.log('Пожалуйста, введите корректное неотрицательное число');
} else {
    let factorial = 1;
    
    for (let i = 1; i <= num; i++) {
        factorial *= i;
    }
    
    console.log(`Факториал числа ${num}! = ${factorial}`);
}

// ===================================
// Задача 3
// Шахматная доска 8x8
// ===================================
console.log('\n=== Задача 3: Шахматная доска 8x8 ===');

let board = '';

for (let row = 0; row < 8; row++) {
    for (let col = 0; col < 8; col++) {
        // Если сумма индексов чётная - ставим #, иначе пробел
        if ((row + col) % 2 === 0) {
            board += '#';
        } else {
            board += ' ';
        }
    }
    board += '\n'; // Переход на новую строку после каждой строки доски
}

console.log(board);
